if (cmd === '--stale') stale();
else if (cmd === '--stamp') stamp(rest);
else {
  console.log('Generating docs/development/generated/ …');
  genFiles(); genCommands(); genEvents(); genSymbols(); genDeps(); genSchema(); genCss(); genConfig(); genTests();
}
