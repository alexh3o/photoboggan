/** files.md : inventory with line counts and the leading comment of each source file. */
function genFiles() {
  const TEXT = /\.(js|mjs|css|rs|json|jsonc|toml|html|md|yml|wxl)$/;
  const SKIP = /(^|\/)(package-lock\.json|Cargo\.lock|gen\/|icons\/|vendor\/|dev_tools\/|screenshots\/|\.claude\/)/;
  const rows = {};
  for (const f of files) {
    if (!TEXT.test(f) || SKIP.test(f)) continue;
    const src = read(f), n = src.split('\n').length;
    let desc = '';
    if (/\.(js|mjs|css|rs)$/.test(f)) {
      const ls = src.split('\n');
      const buf = [];
      let inBlock = false;
      for (const l of ls) {
        const t = l.trim();
        if (inBlock) { buf.push(t.replace(/\*\/.*$/, '').replace(/^\*\s?/, '')); if (t.includes('*/')) break; continue; }
        if (t.startsWith('#!') || t === '') { if (buf.length) break; continue; }
        if (t.startsWith('/*')) { buf.push(t.replace(/^\/\*+\s?/, '').replace(/\*\/.*$/, '')); if (!t.includes('*/')) inBlock = true; else break; continue; }
        if (t.startsWith('//')) { buf.push(t.replace(/^\/\/[/!]?\s?/, '')); continue; }
        break;
      }
      desc = cut(buf.join(' ').replace(/\s+/g, ' ').trim(), 220);
    }
    const dir = f.includes('/') ? f.slice(0, f.lastIndexOf('/')) : '(root)';
    (rows[dir] ??= []).push({ f, n, desc });
  }
  let body = '';
  for (const dir of Object.keys(rows).sort()) {
    body += `\n## ${dir}\n\n| File | Lines | Leading comment |\n|---|---:|---|\n`;
    for (const r of rows[dir].sort((a, b) => a.f.localeCompare(b.f))) body += `| \`${basename(r.f)}\` | ${r.n} | ${esc(r.desc)} |\n`;
  }
  write('files.md', 'File inventory', 'Text files of the repository (vendored files, icons, lock files and `dev_tools/` excluded) with their size and the first comment found at the top of the file. The role of each file is explained in `../code-map.md`.', body);
}

/** ipc-commands.md : Tauri commands, registration check and JS callers. */
function genCommands() {
  const mainRs = read('src-tauri/src/main.rs');
  const hi = mainRs.indexOf('generate_handler![');
  const registered = new Set(mainRs.slice(hi + 'generate_handler!['.length, mainRs.indexOf(']', hi)).replace(/\/\/.*$/gm, '').split(',').map((s) => s.trim().split('::').pop()).filter(Boolean));

  const cmds = [];
  for (const f of rsFiles) {
    const src = read(f);
    const re = /#\[tauri::command([^\]]*)\][\s\S]*?\bfn\s+(\w+)\s*(?:<[^>]*>)?\s*\(/g;
    let m;
    while ((m = re.exec(src))) {
      const open = m.index + m[0].length - 1, close = matchParen(src, open);
      const params = splitTop(src.slice(open + 1, close)).filter((p) => !/:\s*(?:tauri::)?(State|AppHandle|Window|WebviewWindow)\b/.test(p));
      const ret = (src.slice(close + 1).match(/^\s*->\s*([^{]+)/)?.[1] ?? '').replace(/\s+/g, ' ').trim().replace(/^Result<([\s\S]*),\s*String>$/, '$1');
      const isAsync = /\basync\b/.test(m[1]) || /\basync\s+fn\b/.test(m[0]);
      cmds.push({ name: m[2], file: f, line: lineOf(src, m.index), params, ret: ret || '()', pool: isAsync });
    }
  }

  // A command counts as referenced when its name appears as a string literal in the frontend: direct `invoke('x')`, or through a wrapper
  // (`command: 'x'` for tasks, `runLocked('x', …)`). Comments are ignored.
  const callers = new Map();
  const names = new Set(cmds.map((c) => c.name));
  for (const f of [...jsFiles, 'index.html']) {
    const src = read(f).split('\n').filter((l) => !/^\s*(\/\/|\*)/.test(l)).join('\n');
    for (const m of src.matchAll(/['"`](\w+)['"`]/g)) {
      if (!names.has(m[1])) continue;
      const c = callers.get(m[1]) ?? new Map();
      c.set(basename(f), (c.get(basename(f)) ?? 0) + 1);
      callers.set(m[1], c);
    }
  }
  const direct = new Set();
  for (const f of [...jsFiles, 'index.html']) for (const m of read(f).matchAll(/\binvoke\(\s*['"`](\w+)['"`]/g)) direct.add(m[1]);

  cmds.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
  let body = '| Command | Defined in | Args (Rust names; JS passes camelCase) | Returns | Runs on | Referenced from (JS file ×count) |\n|---|---|---|---|---|---|\n';
  for (const c of cmds) {
    const cl = [...(callers.get(c.name) ?? [])].map(([f, n]) => `${f}${n > 1 ? ' ×' + n : ''}`).join(', ') || '—';
    body += `| \`${c.name}\` | \`${mdEscapeRoot(c.file)}\` | ${c.params.length ? esc('`' + c.params.join(', ') + '`') : '—'} | ${esc('`' + c.ret + '`')} | ${c.pool ? 'async pool' : 'main thread'} | ${cl} |\n`;
  }
  const defined = new Set(cmds.map((c) => c.name));
  const notReg = cmds.filter((c) => !registered.has(c.name)).map((c) => c.name);
  const noCaller = cmds.filter((c) => !callers.has(c.name)).map((c) => c.name);
  const ghost = [...direct].filter((n) => !defined.has(n));
  body += `\n## Consistency checks\n\n- Commands defined but **not registered** in \`generate_handler!\` (main.rs): ${notReg.length ? notReg.map((n) => '`' + n + '`').join(', ') : 'none'}\n`;
  body += `- Commands with **no string-literal reference** in the frontend (called through a computed name, or dead): ${noCaller.length ? noCaller.map((n) => '`' + n + '`').join(', ') : 'none'}\n`;
  body += `- \`invoke('name')\` calls whose command **does not exist** in Rust: ${ghost.length ? ghost.map((n) => '`' + n + '`').join(', ') : 'none'}\n`;
  write('ipc-commands.md', `IPC commands (${cmds.length})`, 'Every `#[tauri::command]` of the backend, with its frontend callers. "Runs on": `main thread` = plain `fn` command (blocks the UI thread: keep it light, see AGENTS.md §7); `async pool` = `#[tauri::command(async)]` or `async fn`. Injected parameters (`State`, `AppHandle`, `Window`) are omitted. A reference is any string literal equal to the command name (direct `invoke` or a task wrapper such as the `command:` field of a task); computed names are not detected.', body);
}

/** events.md : backend → frontend events. */
function genEvents() {
  const emit = new Map(), listen = new Map();
  const add = (m, k, f) => m.set(k, new Set([...(m.get(k) ?? []), basename(f)]));
  for (const f of rsFiles) {
    const src = read(f);
    for (const m of src.matchAll(/\.emit\(\s*"([^"]+)"/g)) add(emit, m[1], f);
    for (const m of src.matchAll(/\.emit_to\([^,]+,\s*"([^"]+)"/g)) add(emit, m[1], f);
  }
  for (const f of jsFiles) for (const m of read(f).matchAll(/\b(?:listen|once|listenToBackend)\(\s*['"`]([\w:.-]+)['"`]/g)) add(listen, m[1], f);
  let body = '| Event | Emitted by (Rust) | Listened to by (JS) |\n|---|---|---|\n';
  for (const k of [...new Set([...emit.keys(), ...listen.keys()])].sort()) body += `| \`${k}\` | ${[...(emit.get(k) ?? [])].join(', ') || '—'} | ${[...(listen.get(k) ?? [])].join(', ') || '—'} |\n`;
  write('events.md', 'Backend ↔ frontend events', 'Events emitted with `emit` / `emit_to` and listened to with `listen` / `once`. Payload types are in the emitting Rust file (search the event name).', body);
}

/** symbols-js.md / symbols-rust.md : top-level symbols per file, with line numbers and the comment above. */
function genSymbols() {
  let js = '';
  for (const f of jsFiles.sort()) {
    const syms = jsSymbols(read(f));
    if (!syms.length) continue;
    js += `\n## ${f} (${syms.length})\n\n`;
    for (const s of syms) js += `- \`${s.exported ? 'export ' : ''}${s.name}(${cut((s.params ?? '').replace(/\s+/g, ' '), 60)})\` · L${s.line}${s.doc ? ' — ' + s.doc : ''}\n`;
  }
  write('symbols-js.md', 'Frontend symbols', 'Top-level functions and classes of each `src/*.js` file, in file order (so the list also reads as a map of the file), with the first line of the comment above. Line numbers are valid only for the commit that generated this file: search the name instead of trusting them.', js);

  let rs = '';
  for (const f of rsFiles.sort()) {
    const syms = rsSymbols(read(f));
    if (!syms.length) continue;
    rs += `\n## ${mdEscapeRoot(f)} (${syms.length})\n\n`;
    for (const s of syms) rs += `- ${s.kind ? '*' + s.kind + '* ' : ''}\`${s.pub ? 'pub ' : ''}${s.name}\` · L${s.line}${s.doc ? ' — ' + s.doc : ''}\n`;
  }
  write('symbols-rust.md', 'Backend symbols', 'Functions (free and `impl` methods), structs, enums and traits of each `src-tauri/src/*.rs` file, in file order, test modules excluded. Signatures of IPC commands are in `ipc-commands.md`.', rs);
}

/** module-deps.md : who uses whom, Rust (crate::) and frontend (import). */
function genDeps() {
  const mods = new Set(rsFiles.map((f) => basename(f, '.rs')).filter((n) => n !== 'main'));
  const uses = new Map();
  for (const f of rsFiles) {
    const name = basename(f, '.rs');
    const set = new Set();
    for (const m of read(f).matchAll(/\bcrate::(\w+)/g)) set.add(mods.has(m[1]) ? m[1] : 'main');
    set.delete(name);
    uses.set(name, set);
  }
  const usedBy = (map, n) => [...map].filter(([, s]) => s.has(n)).map(([k]) => k).sort();
  let body = '## Backend (`crate::` references)\n\n`main` stands for the crate root (`main.rs`: AppState, ScanProgress, shared helpers). Test modules excluded.\n\n| Module | Uses | Used by |\n|---|---|---|\n';
  for (const [n, s] of [...uses].sort(([a], [b]) => a.localeCompare(b))) body += `| \`${n}\` | ${[...s].sort().join(', ') || '—'} | ${usedBy(uses, n).join(', ') || '—'} |\n`;

  const jsUses = new Map();
  for (const f of jsFiles) {
    const set = new Set();
    for (const m of read(f).matchAll(/(?:from|import)\s*\(?\s*['"]\.\/([\w.-]+?)(?:\.js)?['"]/g)) if (!m[1].endsWith('.css') && !m[1].endsWith('.json') && !m[1].endsWith('.jsonc')) set.add(m[1]);
    set.delete(basename(f, '.js'));
    jsUses.set(basename(f, '.js'), set);
  }
  body += '\n## Frontend (`import` of `./x.js`)\n\n| Module | Imports | Imported by |\n|---|---|---|\n';
  for (const [n, s] of [...jsUses].sort(([a], [b]) => a.localeCompare(b))) body += `| \`${n}\` | ${[...s].sort().join(', ') || '—'} | ${usedBy(jsUses, n).join(', ') || '—'} |\n`;
  write('module-deps.md', 'Module dependencies', 'Static dependency graph, to evaluate the consequences of a change before making it. Dynamic access (events, `invoke`) is not here: see `ipc-commands.md` and `events.md`.', body);
}

/** db-schema.md : tables, indexes, migrations found in SQL strings. */
function genSchema() {
  let tables = '', indexes = '', alters = '';
  for (const f of rsFiles.sort()) {
    const src = read(f);
    for (const m of src.matchAll(/CREATE (?:VIRTUAL )?TABLE IF NOT EXISTS (\w+)\s*\(/g)) {
      const open = m.index + m[0].length - 1, close = matchParen(src, open);
      const cols = splitTop(src.slice(open + 1, close).replace(/\\n/g, ' '));
      tables += `\n### ${m[1]}  \`${mdEscapeRoot(f)}\`\n\n\`\`\`sql\n${cols.map((c) => '  ' + c).join('\n')}\n\`\`\`\n`;
    }
    for (const m of src.matchAll(/CREATE (UNIQUE )?INDEX IF NOT EXISTS (\w+)\s+ON\s+(\w+)\s*\(([^)]*)\)/g)) indexes += `- \`${m[2]}\` on \`${m[3]}(${m[4].trim()})\`${m[1] ? ' (unique)' : ''} · ${mdEscapeRoot(f)}\n`;
    for (const m of src.matchAll(/ALTER TABLE (\w+) ADD COLUMN (\w+)\s*([^"';)]*)/g)) alters += `- \`${m[1]}.${m[2]}\` ${m[3].trim()} · ${mdEscapeRoot(f)}\n`;
  }
  write('db-schema.md', 'SQLite schema', 'Extracted from the `CREATE TABLE` / `CREATE INDEX` / `ALTER TABLE … ADD COLUMN` strings of the Rust code. A column added by a migration appears both here (migrations) and, for new databases, possibly in the table definition. What each table is for, and which are rebuildable from the folders on disk, is explained in the module docs.', `## Tables\n${tables}\n## Indexes\n\n${indexes || 'none'}\n\n## Column migrations (ALTER TABLE)\n\n${alters || 'none'}`);
}

/** css.md : section comments per file, custom properties, z-index scale. */
function genCss() {
  const varDefs = new Map(), zs = [];
  let sections = '';
  for (const f of cssFiles.sort()) {
    const raw = read(f), lines = raw.split('\n');
    const heads = [];
    lines.forEach((l, i) => { const m = l.match(/^\/\*+\s*(.*?)\s*(\*\/)?$/); if (m && m[1] && !/^[=*\-]+$/.test(m[1])) heads.push(`- L${i + 1} ${cut(m[1].replace(/\s*\*\/\s*$/, ''), 130)}`); });
    sections += `\n### ${f} (${lines.length} lines)\n\n${heads.join('\n') || '_no column-0 comments_'}\n`;
    const stripped = raw.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, ' ')); // keep line numbers
    for (const m of stripped.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const sel = m[1].replace(/\s+/g, ' ').trim(), decl = m[2];
      for (const v of decl.matchAll(/(--[\w-]+)\s*:\s*([^;]+)/g)) {
        const e = varDefs.get(v[1]) ?? [];
        e.push({ f: basename(f), sel: cut(sel, 50), val: cut(v[2].trim(), 40), light: /light/.test(sel) });
        varDefs.set(v[1], e);
      }
      const z = decl.match(/z-index\s*:\s*(-?\d+|var\([^)]*\))/);
      if (z) zs.push({ z: z[1], f: basename(f), sel: cut(sel, 80) });
    }
  }
  const runtime = new Map(), used = new Map();
  for (const f of [...jsFiles, ...cssFiles, 'index.html']) {
    const src = read(f);
    for (const m of src.matchAll(/setProperty\(\s*['"`](--[\w-]+)/g)) runtime.set(m[1], new Set([...(runtime.get(m[1]) ?? []), basename(f)]));
    for (const m of src.matchAll(/var\((--[\w-]+)/g)) used.set(m[1], (used.get(m[1]) ?? 0) + 1);
  }
  let vars = '| Variable | Defined in (file · selector · value) | Used | Set at runtime by |\n|---|---|---:|---|\n';
  for (const n of [...new Set([...varDefs.keys(), ...runtime.keys()])].sort()) {
    const d = (varDefs.get(n) ?? []).map((x) => `${x.f} · ${x.light ? '(light) ' : ''}\`${x.sel}\` · \`${x.val}\``).join('<br>');
    vars += `| \`${n}\` | ${esc(d || '—')} | ${used.get(n) ?? 0} | ${[...(runtime.get(n) ?? [])].join(', ') || '—'} |\n`;
  }
  const zNum = (v) => (/^-?\d+$/.test(v) ? Number(v) : -1e9);
  zs.sort((a, b) => zNum(b.z) - zNum(a.z));
  const zt = '| z-index | File | Selector |\n|---:|---|---|\n' + zs.map((z) => `| ${z.z} | ${z.f} | ${esc('`' + z.sel + '`')} |`).join('\n');
  write('css.md', 'CSS: custom properties, z-index scale, sections', 'Custom properties (`--x`) with every place they are defined (theme overrides marked `(light)`), how often they are read, and whether JS sets them at runtime; then the z-index stack (highest first); then the column-0 section comments of each stylesheet, as a map of the file. Design rules (rem / px, themes) are in `../style.md`.', `## Custom properties\n\n${vars}\n## z-index stack\n\n${zt}\n\n## Sections per stylesheet\n${sections}`);
}

/** config.md : defaults.jsonc, localStorage keys, i18n coverage, dependencies. */
function genConfig() {
  // defaults.jsonc
  const defaultsSrc = read('src/defaults.jsonc');
  let defaults = {};
  try { defaults = JSON.parse(defaultsSrc.split('\n').filter((l) => !/^\s*\/\//.test(l)).join('\n')); }
  catch { for (const m of defaultsSrc.matchAll(/^\s{2}"(\w+)"\s*:\s*(.*?),?\s*$/gm)) defaults[m[1]] = m[2]; }
  const keyFiles = new Map();
  for (const f of jsFiles) {
    const src = read(f);
    for (const m of src.matchAll(/localStorage\.(?:get|set|remove)Item\(\s*['"`]([\w.-]+)['"`]/g)) addKey(m[1], f);
    for (const m of src.matchAll(/\bread(?:Bool|Choice|Number)\(\s*['"`]([\w.-]+)['"`]/g)) addKey(m[1], f);
    for (const m of src.matchAll(/\bDEFAULTS\.(\w+)/g)) addKey(m[1], f);
  }
  function addKey(k, f) { keyFiles.set(k, new Set([...(keyFiles.get(k) ?? []), basename(f)])); }
  let cfg = '| Key | Default (`defaults.jsonc`) | Read / written in |\n|---|---|---|\n';
  for (const k of [...new Set([...Object.keys(defaults), ...keyFiles.keys()])].sort()) {
    const d = k in defaults ? '`' + cut(JSON.stringify(defaults[k]) ?? String(defaults[k]), 50) + '`' : '**none** (AGENTS.md §5.G: every remembered setting needs a default)';
    cfg += `| \`${k}\` | ${esc(d)} | ${[...(keyFiles.get(k) ?? [])].join(', ') || '—'} |\n`;
  }

  // i18n
  const en = JSON.parse(read('src/locales/en.json')), fr = JSON.parse(read('src/locales/fr.json'));
  const base = (k) => k.replace(/\|\w+$/, '');
  const enB = new Set(Object.keys(en).map(base)), frB = new Set(Object.keys(fr).map(base));
  const used = new Set();
  for (const f of [...jsFiles, 'index.html']) {
    // Comments are skipped: they may quote placeholder keys (e.g. `t('Clé')` in i18n.js).
    const src = read(f).replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/<!--[\s\S]*?-->/g, '');
    for (const m of src.matchAll(/\b(?:t|tp|labelWithColon)\(\s*'([^'$]+)'/g)) used.add(m[1]);
    for (const m of src.matchAll(/data-i18n(?:-title|-aria-label|-placeholder)?="([^"$]+)"/g)) used.add(m[1]);
  }
  const list = (a) => (a.length ? a.map((k) => '`' + k + '`').join(', ') : 'none');
  const i18n = `- Keys: ${Object.keys(en).length} (en) / ${Object.keys(fr).length} (fr)\n- In en.json but missing from fr.json: ${list([...enB].filter((k) => !frB.has(k)))}\n- In fr.json but missing from en.json: ${list([...frB].filter((k) => !enB.has(k)))}\n- Used with a literal key in the code but missing from en.json (dynamic keys are not detected): ${list([...used].filter((k) => !enB.has(k)).sort())}\n`;

  // dependencies / scripts
  const cargo = read('src-tauri/Cargo.toml');
  const deps = (cargo.match(/\[dependencies\]([\s\S]*?)(?=\n\[|$)/)?.[1] ?? '').split('\n').filter((l) => /^[\w-]+\s*=/.test(l)).map((l) => '- `' + cut(l.replace(/\s+/g, ' '), 140) + '`').join('\n');
  const pkg = JSON.parse(read('package.json'));
  const scripts = Object.entries(pkg.scripts).map(([k, v]) => `- \`npm run ${k}\` → \`${v}\``).join('\n');
  const npmDeps = Object.entries({ ...pkg.dependencies, ...pkg.devDependencies }).map(([k, v]) => `- \`${k}\` ${v}`).join('\n');

  write('config.md', 'Configuration, i18n coverage, dependencies', 'Settings remembered in `localStorage` and their defaults (`src/defaults.jsonc`), translation coverage, and declared dependencies. Keys read through a variable are not detected.', `## Remembered settings\n\n${cfg}\n## Translations\n\n${i18n}\n## npm scripts\n\n${scripts}\n\n## npm dependencies\n\n${npmDeps}\n\n## Rust dependencies (Cargo.toml)\n\n${deps}`);
}

/** tests.md : inventory of backend tests. */
function genTests() {
  let body = '', total = 0, ign = 0;
  for (const f of testFiles.sort()) {
    const lines = read(f).split('\n');
    const head = lines.filter((l) => l.startsWith('//!')).map((l) => l.replace(/^\/\/!\s?/, '')).join(' ');
    const names = [];
    let isTest = false, ignore = null;
    for (const l of lines) {
      if (/^\s*#\[test\]/.test(l)) isTest = true;
      const mi = l.match(/^\s*#\[ignore(?:\s*=\s*"([^"]*)")?\]/);
      if (mi) ignore = mi[1] ?? 'ignored';
      const mf = l.match(/^\s*(?:pub\s+)?fn\s+(\w+)/);
      if (mf && isTest) { names.push({ n: mf[1], ignore }); isTest = false; ignore = null; }
      else if (mf) ignore = null;
    }
    total += names.length; ign += names.filter((x) => x.ignore).length;
    // Owner = the module that includes this file with #[path = "tests/<name>"] (faces.rs includes faces_db.rs), else the same-name module.
    const owner = files.find((m) => /^src-tauri\/src\/[^/]+\.rs$/.test(m) && read(m).includes(`"tests/${basename(f)}"`));
    const target = owner ? basename(owner) : existsSync(join(ROOT, 'src-tauri/src', basename(f))) ? basename(f) : '—';
    body += `\n## ${basename(f)} — ${names.length} test(s), tests \`src-tauri/src/${target.replace(/`/g, '')}\`\n\n${head ? cut(head, 400) + '\n\n' : ''}${names.map((x) => `- \`${x.n}\`${x.ignore ? ` — **ignored**: ${x.ignore}` : ''}`).join('\n') || '_no #[test]_'}\n`;
  }
  const fixtures = files.filter((f) => f.startsWith('src-tauri/src/tests/fixtures/')).length;
  write('tests.md', `Backend tests (${total}, ${ign} ignored)`, `One \`src-tauri/src/tests/<module>.rs\` per tested module, declared at the end of the module with \`#[cfg(test)] #[path = …] mod tests;\`. Run: \`cd src-tauri && cargo test\` (fast set) and \`cargo test exiftool:: -- --ignored --test-threads=1\` (needs ExifTool, see \`npm run fetch-exiftool\`). Fixtures: ${fixtures} file(s) in \`tests/fixtures/\`; synthetic helpers in \`test_support.rs\`. There is no frontend test suite.`, body);
}

