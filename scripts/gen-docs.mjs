function handDocs() {
  return files.filter((f) => /^docs\/development\/.+\.md$/.test(f) && !f.includes('/generated/') && !basename(f).startsWith('_')).map((f) => {
    const m = read(f).split('\n')[0].match(/^<!--\s*verified:\s*(\S+)\s*\|\s*sources:\s*([^>]*?)\s*-->/);
    return { f, hash: m?.[1] ?? null, sources: m ? m[2].split(',').map((s) => s.trim()).filter(Boolean) : [] };
  });
}

// A source is a file (any change counts) or a directory ending in "/" (only added / deleted / renamed files count: it tracks structure, not content).
const covers = (src, path) => path === src;

function stale() {
  const docs = handDocs();
  let bad = 0;
  for (const d of docs) {
    if (!d.hash) { console.log(`?  ${d.f}: no "<!-- verified: <hash> | sources: … -->" first line`); bad++; continue; }
    if (d.hash === 'none') { console.log(`…  ${d.f}: not written yet`); continue; }
    let changed;
    try { changed = git('diff', '--name-status', d.hash).split('\n').filter(Boolean).map((l) => { const [st, ...p] = l.split('\t'); return { st, paths: p }; }); }
    catch { console.log(`?  ${d.f}: unknown commit ${d.hash}`); bad++; continue; }
    const hit = changed.flatMap(({ st, paths }) => paths.filter((p) => d.sources.some((s) => (s.endsWith('/') ? p.startsWith(s) && /^[ADR]/.test(st) : covers(s, p)))));
    if (hit.length) { console.log(`!  ${d.f} (verified ${d.hash}): ${hit.length} source(s) changed → ${hit.join(', ')}`); bad++; }
    else console.log(`ok ${d.f}`);
  }
  const allSources = docs.flatMap((d) => d.sources).filter((s) => !s.endsWith('/'));
  const uncovered = [...rsFiles, ...jsFiles, ...cssFiles].filter((f) => !allSources.some((s) => covers(s, f)));
  if (uncovered.length) console.log(`\nSource files listed by no doc (add them to a "sources:" line):\n  ${uncovered.join('\n  ')}`);
  process.exit(bad ? 1 : 0);
}

function stamp(paths) {
  const head = git('rev-parse', '--short', 'HEAD').trim();
  for (const p of paths) {
    const abs = join(ROOT, p);
    const txt = readFileSync(abs, 'utf8');
    const out = txt.replace(/^(<!--\s*verified:\s*)\S+/, `$1${head}`);
    if (out === txt) console.log(`unchanged (no header?): ${p}`); else { writeFileSync(abs, out); console.log(`stamped ${p} → ${head}`); }
  }
}

