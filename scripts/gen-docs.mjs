function jsSymbols(src) {
  const lines = src.split('\n'), out = [];
  lines.forEach((l, i) => {
    let m;
    if ((m = l.match(/^(export\s+)?(?:default\s+)?(async\s+)?function\s*\*?\s*([\w$]+)\s*\(([^)]*)/))) out.push({ name: m[3], params: m[4], exported: !!m[1], line: i + 1, doc: docAbove(lines, i, false) });
    else if ((m = l.match(/^(export\s+)?const\s+([\w$]+)\s*=\s*(?:async\s*)?(?:\(([^)]*)\)|([\w$]+))\s*=>/))) out.push({ name: m[2], params: m[3] ?? m[4], exported: !!m[1], line: i + 1, doc: docAbove(lines, i, false) });
    else if ((m = l.match(/^(export\s+)?class\s+([\w$]+)/))) out.push({ name: m[2], params: '', exported: !!m[1], line: i + 1, doc: docAbove(lines, i, false), kind: 'class' });
  });
  return out;
}

function rsSymbols(src) {
  const lines = src.split('\n'), out = [];
  let impl = null;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^#\[cfg\(test\)\]/.test(l) && /^(#\[path|mod tests)/.test(lines[i + 1] ?? '')) break; // end of production code
    const mi = l.match(/^impl(?:<[^>]*>)?\s+(?:[\w:<>, ]+\s+for\s+)?([\w:]+)/);
    if (mi && l.trimEnd().endsWith('{')) impl = mi[1];
    else if (l === '}') impl = null;
    const mf = l.match(/^(\s*)(pub(?:\([^)]*\))?\s+)?(?:async\s+)?(?:unsafe\s+)?(?:const\s+)?fn\s+(\w+)/);
    if (mf && (mf[1] === '' || (impl && mf[1] === '    '))) out.push({ name: (mf[1] === '' ? '' : impl + '::') + mf[3], pub: !!mf[2], line: i + 1, doc: docAbove(lines, i, true) });
    const mt = l.match(/^(pub(?:\([^)]*\))?\s+)?(struct|enum|trait)\s+(\w+)/);
    if (mt) out.push({ name: mt[3], pub: !!mt[1], line: i + 1, doc: docAbove(lines, i, true), kind: mt[2] });
  }
  return out;
}

