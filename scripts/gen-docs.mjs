#!/usr/bin/env node
// Developer documentation helper (see docs/development/README.md).
//
//   node scripts/gen-docs.mjs                 Regenerate docs/development/generated/*.md from the source code (deterministic, no timestamps).
//   node scripts/gen-docs.mjs --stale         List hand-written docs whose source files changed since their "verified" commit, and sources no doc covers.
//   node scripts/gen-docs.mjs --stamp <doc>…  Set the "verified" commit of the given docs to the current HEAD (after reviewing them against the code).
//
// Regex-based on purpose: no dependency, no build step. It extracts what the code states (signatures, names, tables, variables); it never guesses intent.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = join(ROOT, 'docs', 'development');
const OUT = join(DOCS, 'generated');

const read = (p) => readFileSync(join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 26 }).replace(/\r\n/g, '\n');
const esc = (s) => String(s).replace(/\|/g, '\\|');
const cut = (s, n) => (s.length > n ? s.slice(0, n - 1) + '…' : s);
const lineOf = (src, idx) => src.slice(0, idx).split('\n').length;

// Tracked + new (not ignored) files, minus files deleted from the working tree.
const files = git('ls-files', '--cached', '--others', '--exclude-standard').split('\n').filter((f) => f && existsSync(join(ROOT, f)));
const rsFiles = files.filter((f) => /^src-tauri\/src\/[^/]+\.rs$/.test(f));
const testFiles = files.filter((f) => /^src-tauri\/src\/tests\/[^/]+\.rs$/.test(f));
const jsFiles = files.filter((f) => /^src\/[^/]+\.js$/.test(f));
const cssFiles = files.filter((f) => /^src\/[^/]+\.css$/.test(f));
const mdEscapeRoot = (s) => s.replace(/^src-tauri\/src\//, '');

// ----------------------------------------------------------------------------------------------------------------------------------------
// Small parsing helpers
// ----------------------------------------------------------------------------------------------------------------------------------------

/** Index of the parenthesis closing the one at `open`, or -1. */
function matchParen(s, open) {
  let d = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === '(') d++;
    else if (s[i] === ')' && --d === 0) return i;
  }
  return -1;
}

/** Split on commas that are not nested in (), <>, [] or {}. */
function splitTop(s) {
  const out = [];
  let d = 0, cur = '';
  for (const c of s) {
    if ('(<[{'.includes(c)) d++;
    else if (')>]}'.includes(c)) d--;
    if (c === ',' && d === 0) { out.push(cur); cur = ''; } else cur += c;
  }
  if (cur.trim()) out.push(cur);
  return out.map((x) => x.replace(/\s+/g, ' ').trim()).filter(Boolean);
}

/** First line of the comment block sitting directly above line `i` (0-based), without its marker. */
function docAbove(lines, i, isRust) {
  let j = i - 1;
  while (j >= 0 && (isRust ? /^\s*#\[/.test(lines[j]) : false)) j--; // skip Rust attributes
  let top = -1;
  while (j >= 0 && /^\s*(\/\/|\/\*|\*)/.test(lines[j])) { top = j; j--; }
  if (top < 0) return '';
  return cut(lines[top].replace(/^\s*(\/\/[/!]?|\/\*+|\*)\s?/, '').replace(/\*\/\s*$/, '').trim(), 140);
}

function write(name, title, intro, body) {
  mkdirSync(OUT, { recursive: true });
  const text = `<!-- GENERATED by scripts/gen-docs.mjs : do not edit by hand. Regenerate with \`npm run docs:gen\`. -->\n# ${title}\n\n${intro}\n\n${body.trim()}\n`;
  writeFileSync(join(OUT, name), text);
  console.log(`  ${name} (${text.split('\n').length} lines)`);
}

